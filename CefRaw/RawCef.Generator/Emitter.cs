                    // Merge size_t + InputArray
                    if (IsSizeType(nativeType) && i + 1 < nativeArgTypes.Length
                                               && paramKinds.Count > i + 1 &&
                                               paramKinds[i + 1] == TypeMapper.ParamKind.InputArray)
                    {
