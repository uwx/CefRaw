    private static void EmitBridgeMethod(IndentedStringBuilder sb, StructDefinition structDef, FieldDefinition method)
    {
        var nativeName = structDef.Name;
        var managedName = TypeMapper.GetManagedName(structDef.Name);
        var (args, @return) = TypeMapper.GetTypeListFromDelegate(method.Type.CSharpType);
        var paramKinds = TypeMapper.ClassifyParams(method.Type.Native!);

        var nativeReturnType = @return;
        var nativeArgTypes = args.ToArray();

        var returnManaged = TypeMapper.MapNativeToManaged(@return, out var returnIsString, out var returnIsCefObject, out var returnCefObjectName, out var returnIsBasetime);

        var bridgeName = $"Bridge_{TypeMapper.SnakeToPascal(method.Name)}";

        // Platform-specific attribute, shared method body
        sb.AppendLine("#if OS_WIN");
        sb.AppendLine("[UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvStdcall) })]");
        sb.AppendLine("#else");
        sb.AppendLine("[UnmanagedCallersOnly(CallConvs = new[] { typeof(CallConvCdecl) })]");
        sb.AppendLine("#endif");
        sb.Append($"private static {nativeReturnType} {bridgeName}({nativeArgTypes[0]} self");

        for (int i = 1; i < nativeArgTypes.Length; i++)
            sb.Append($", {nativeArgTypes[i]} arg{i - 1}");
        sb.AppendLine(")");

