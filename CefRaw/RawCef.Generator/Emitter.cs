using System.Collections.Generic;
using System.Text;
using CefRaw.BindingsParser.Models;
using WorldXaml.Generator.Common;

namespace CefRaw.SourceGen;

/// <summary>
/// Emits C# source text for managed wrapper classes from extracted CEF struct models.
/// </summary>
internal static class Emitter
{
    public static string GenerateNative(StructDefinition structDef)
    {
        var sb = new IndentedStringBuilder();

        // Header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace RawCef.Native;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Managed binding for the {structDef.Name} struct.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"{structDef.Access} unsafe partial struct {structDef.Name}");
        sb.AppendLine("{");
        using (sb.Indent())
        {
            foreach (var field in structDef.Fields)
            {
                sb.AppendLine("/// <summary>");
                sb.AppendLine($"/// Managed binding for the {field.Name} field.");
                sb.AppendLine("/// </summary>");
                sb.AppendLine("/// <remarks>");
                sb.AppendLine($"/// Native type: <code>{field.Type.Native}</code>");
                sb.AppendLine("/// </remarks>");
                sb.AppendLine($"{field.Access} {field.Type.CSharpType} {field.Name};");
            }
        }
        sb.AppendLine("}");

        return sb.ToString();
    }
    
    public static string GenerateWrapper(StructDefinition structDef)
    {
        var sb = new IndentedStringBuilder();

        var nativeName = structDef.Name;
        var managedName = TypeMapper.GetManagedName(structDef.Name);

        // Header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using RawCef.Native;");
        sb.AppendLine();
        sb.AppendLine("namespace RawCef;");
        sb.AppendLine();

        // Class declaration
        var baseClass = GetBaseType(structDef) switch
        {
            "_cef_base_ref_counted_t" => "CefBaseRefCounted",
            "_cef_base_scoped_t" => "CefBaseScoped",
            _ => null
        };

        sb.Append($"public unsafe partial class {managedName}");
        if (baseClass != null)
            sb.Append($" : {baseClass}");
        sb.AppendLine();
        
        sb.AppendLine("{");

        using (sb.Indent())
        {
            // Private pointer field
            sb.Append($"private readonly {nativeName}* _ptr;");
            sb.AppendLine();

            // Constructor
            sb.AppendLine();
            sb.Append($"public {managedName}({nativeName}* ptr)");
            if (baseClass != null)
            {
                sb.Append(" : base(&ptr->@base)");
            }

            sb.AppendLine();
            sb.AppendLine("{");
            sb.AppendLine("    _ptr = ptr;");
            sb.AppendLine("    Initialize();");
            sb.AppendLine("}");
            sb.AppendLine();
            sb.AppendLine("partial void Initialize();");

            // Internal pointer accessor for other wrappers
            sb.AppendLine();
            sb.AppendLine($"internal {nativeName}* NativePtr => _ptr;");

            // Methods for function-pointer fields
            foreach (var field in structDef.Fields.Where(field => field.Type.CSharpType.Contains("delegate*")))
            {
                sb.AppendLine();
                EmitMethod(sb, structDef, field);
            }

            // Properties for data fields (data-only structs)
            foreach (var field in structDef.Fields.Where(field => !field.Type.CSharpType.Contains("delegate*")))
            {
                sb.AppendLine();
                EmitDataProperty(sb, field);
            }
        }

        sb.AppendLine("}");

        return sb.ToString();

        static string? GetBaseType(StructDefinition structDefinition)
        {
            return structDefinition.Fields.FirstOrDefault(f => f.Name == "@base")?.Type.CSharpType;
        }
    }

    private static void EmitMethod(IndentedStringBuilder sb, StructDefinition model, FieldDefinition method)
    {
        var (args, @return) = TypeMapper.GetTypeListFromDelegate(method.Type.CSharpType);

        var returnManaged = TypeMapper.MapNativeToManaged(@return, out var returnIsString, out var returnIsCefObject, out var returnCefObjectName);
        var argsManaged = args
            .Skip(1) // skip instance
            .Select((arg, idx) =>
            {
                var managed =
                    TypeMapper.MapNativeToManaged(arg, out var isString, out var isCefObject, out var cefObjectName);

                return (Native: arg, Managed: managed, IsString: isString, IsCefObject: isCefObject, CefObjectName: cefObjectName, Index: idx);
            })
            .ToArray();
        
        // Method signature
        sb.Append($"public {(returnIsCefObject ? returnCefObjectName : returnManaged)} {TypeMapper.SnakeToPascal(method.Name)}(");

        for (int i = 0; i < argsManaged.Length; i++)
        {
            if (i > 0) sb.Append(", ");
            sb.Append($"{argsManaged[i].Managed} arg{argsManaged[i].Index}");
        }
        sb.AppendLine(")");
        sb.AppendLine("{");

        using (sb.Indent())
        {
            // Collect string params for fixed blocks
            var stringParams = argsManaged.Where(p => p.IsString).ToArray();
            var hasStrings = stringParams.Length > 0;

            // Emit fixed blocks for each string param
            if (hasStrings)
            {
                foreach (var p in stringParams)
                {
                    sb.AppendLine($"fixed (char* _p{p.Index} = arg{p.Index})");
                }

                sb.AppendLine("{");
                sb.IncrementIndent();

                // Declare string struct locals inside fixed block
                foreach (var sp in stringParams)
                {
                    sb.AppendLine($"_cef_string_utf16_t _s{sp.Index};");
                    sb.AppendLine($"CefStringRef.FillFromPinned(&_s{sp.Index}, _p{sp.Index}, arg{sp.Index}?.Length ?? 0);");
                }
            }

            // Marshal parameters: build native arg list
            List<string> nativeArgs = ["_ptr"];

            foreach (var p in argsManaged)
            {
                if (p.IsString)
                {
                    nativeArgs.Add("&_s" + p.Index);
                }
                else if (p.IsCefObject)
                {
                    nativeArgs.Add($"arg{p.Index} is null ? null : arg{p.Index}.NativePtr");
                }
                else
                {
                    nativeArgs.Add($"arg{p.Index}");
                }
            }

            // Call native
            if (returnManaged == "void")
            {
                sb.AppendLine($"_ptr->{method.Name}({string.Join(", ", nativeArgs)});");
            }
            else
            {
                sb.AppendLine($"var _result = _ptr->{method.Name}({string.Join(", ", nativeArgs)});");
                sb.AppendLine();

                // Marshal return
                if (returnIsString)
                {
                    sb.AppendLine("return CefStringRef.ToStringAndFree(_result);");
                }
                else if (returnIsCefObject)
                {
                    sb.AppendLine($"return _result != null ? new {returnCefObjectName}(_result) : null;");
                }
                else
                {
                    sb.AppendLine("return _result;");
                }
            }

            // Close fixed blocks
            if (hasStrings)
            {
                sb.DecrementIndent();
                sb.AppendLine("}");
            }

        }

        sb.AppendLine("}");
    }

    private static void EmitDataProperty(IndentedStringBuilder sb, FieldDefinition field)
    {
        var propName = TypeMapper.SnakeToPascal(field.Name);

        if (TypeMapper.IsStringValueField(field.Type.CSharpType, field.Type.Native))
        {
            // _cef_string_utf16_t embedded by value → CefString wrapper
            // We need to be careful: the CefString holds a pointer to the embedded field
            sb.AppendLine($"    public string? {propName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        get => new CefString(&_ptr->{field.Name}).Value;");
            sb.AppendLine($"        set => new CefString(&_ptr->{field.Name}).Value = value;");
            sb.AppendLine("    }");
        }
        else if (TypeMapper.IsCefEnum(field.Type.CSharpType))
        {
            // Use raw native enum type (no Cef* wrapper yet)
            sb.AppendLine($"    public {field.Type.CSharpType} {propName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        get => _ptr->{field.Name};");
            sb.AppendLine($"        set => _ptr->{field.Name} = value;");
            sb.AppendLine("    }");
        }
        else
        {
            sb.AppendLine($"    public {field.Type.CSharpType} {propName}");
            sb.AppendLine("    {");
            sb.AppendLine($"        get => _ptr->{field.Name};");
            sb.AppendLine($"        set => _ptr->{field.Name} = value;");
            sb.AppendLine("    }");
        }
    }

    public static string GenerateEnum(EnumerationDefinition enumeration)
    {
        var sb = new IndentedStringBuilder();

        // Header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace RawCef.Native;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Managed binding for the {enumeration.Name} enum.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"{enumeration.Access} enum {TypeMapper.GetManagedName(enumeration.Name)} : {enumeration.Type}");
        sb.AppendLine("{");
        using (sb.Indent())
        {
            foreach (var enumerator in enumeration.Enumerators)
            {
                if (enumerator.Value != null)
                {
                    if (enumerator.Value.IsUnchecked)
                    {
                        sb.AppendLine($"{enumerator.Name} = unchecked({enumerator.Value.Code}),");
                    }
                    else
                    {
                        sb.AppendLine($"{enumerator.Name} = {enumerator.Value.Code},");
                    }
                }
                else
                {
                    sb.AppendLine($"{enumerator.Name},");
                }
            }
        }
        sb.AppendLine("}");

        return sb.ToString();
    }
}
