using System.Text.RegularExpressions;
using CefRaw.BindingsParser;
using CefRaw.BindingsParser.Models;
using CefRaw.SourceGen;
using WorldXaml.Generator.Common;

var outputDir = args[0];

var winBindings = BindingsParser.ParseFile("./bindings_win.xml");
var macBindings = BindingsParser.ParseFile("./bindings_mac.xml");
var linuxBindings = BindingsParser.ParseFile("./bindings_linux.xml");

var winStructs = MassageStructs(winBindings.Namespace.Structs);
var macStructs = MassageStructs(macBindings.Namespace.Structs);
var linuxStructs = MassageStructs(linuxBindings.Namespace.Structs);

var groupedStructs = GroupStructs(winStructs, macStructs, linuxStructs);

File.WriteAllText(Path.Combine(outputDir, "GlobalUsings.g.cs"), """
                                                              // <auto-generated/>
                                                              #nullable enable

                                                              """);
foreach (var (name, groups) in groupedStructs)
{
    if (groups.Count == 1)
    {
        var native = Emitter.GenerateNative(groups.First().Struct);
        var managed = Emitter.GenerateWrapper(groups.First().Struct);
        
        File.WriteAllText(Path.Combine(outputDir, "Native", $"{name}.cs"), native);
        File.WriteAllText(Path.Combine(outputDir, "Managed", $"{TypeMapper.GetManagedName(name)}.cs"), managed);
    }
    else
    {
        var native = string.Join("\n",
            groups.Select(e => $"#if OS_{e.Platform!.ToUpperInvariant()}\n" + Emitter.GenerateNative(e.Struct) + "#endif")
        );
        
        File.WriteAllText(Path.Combine(outputDir, "Native", $"{name}.cs"), native);
    }
}

foreach (var enumeration in winBindings.Namespace.Enumerations)
{
    var native = Emitter.GenerateEnum(enumeration);
    
    File.WriteAllText(Path.Combine(outputDir, "Enums", $"{TypeMapper.GetManagedName(enumeration.Name)}.cs"), native);
    
    File.AppendAllText(Path.Combine(outputDir, "GlobalUsings.g.cs"), $"global using {enumeration.Name} = RawCef.Native.{TypeMapper.GetManagedName(enumeration.Name)};\n");
}

var sb = new IndentedStringBuilder();
foreach (var (binding, platform) in (ReadOnlySpan<(BindingsRoot Root, string Platform)>)[(Root: winBindings, Platform: "Win"), (Root: macBindings, Platform: "Mac"), (Root: linuxBindings, Platform: "Linux")])
{
    if (binding.Namespace.Class is { } cls)
    {
        Emitter.GenerateNativeMethods(cls, sb, platform);
    }
}
File.WriteAllText(Path.Combine(outputDir, "CefUnsafe.g.cs"), sb.ToString());

return;

// group differing structs by platform, or null platform if it's the same struct for all platforms
List<(string Name, List<(string? Platform, StructDefinition Struct)>)> GroupStructs(List<StructDefinition> win, List<StructDefinition> mac, List<StructDefinition> linux)
{
    var winGroup = win.Select(s => (Platform: "Win", Struct: s));
    var macGroup = mac.Select(s => (Platform: "Mac", Struct: s));
    var linuxGroup = linux.Select(s => (Platform: "Linux", Struct: s));
    return winGroup
        .Concat(macGroup)
        .Concat(linuxGroup)
        .GroupBy(s => s.Struct.Name)
        .Select(g =>
        {
            if (g.DistinctBy(s => s.Struct).Count() > 1)
            {
                return (g.Key, (List<(string? Platform, StructDefinition Struct)>)[..g]);
            }

            return (g.Key, (List<(string? Platform, StructDefinition Struct)>)
            [
                (Platform: null, Struct: g.First().Struct)
            ]);
        })
        .ToList();
}

// deduplicates structs and extracts all unique fields
List<StructDefinition> MassageStructs(List<StructDefinition> structs)
{
    return structs
        .GroupBy(s => s.Name)
        .Select(s => new StructDefinition
        {
            Name = s.Key,
            Access = s.First().Access,
            Unsafe = s.First().Unsafe,
            Fields = s
                .SelectMany(s1 => s1.Fields)
                .DistinctBy(s1 => s1.Name)
                .ToList()
        })
        .ToList();
}
