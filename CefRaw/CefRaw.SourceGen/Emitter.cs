using System.Collections.Generic;
using System.Text;

namespace CefRaw.SourceGen;

/// <summary>
/// Emits C# source text for managed wrapper classes from extracted CEF struct models.
/// </summary>
internal static class Emitter
{
    public static string GenerateWrapper(CefStructModel model)
    {
        var sb = new StringBuilder();

        // Header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using RawCef.Native;");
        sb.AppendLine();
        sb.AppendLine("namespace RawCef;");
        sb.AppendLine();

        // Class declaration
        var baseClass = model.BaseType switch
        {
            CefBaseType.RefCounted => "CefBaseRefCounted",
            CefBaseType.Scoped => "CefBaseScoped",
            _ => null
        };

        sb.Append("public unsafe partial class ").Append(model.ManagedName);
        if (baseClass != null)
            sb.Append(" : ").Append(baseClass);
        sb.AppendLine();
        sb.AppendLine("{");

        // Private pointer field
        sb.Append("    private readonly ").Append(model.NativeName).Append("* _ptr;");
        sb.AppendLine();

        // Constructor
        sb.AppendLine();
        sb.Append("    public ").Append(model.ManagedName)
          .Append("(").Append(model.NativeName).Append("* ptr)");
        if (baseClass != null)
        {
            sb.Append(" : base(&ptr->@base)");
        }
        sb.AppendLine();
        sb.AppendLine("    {");
        sb.AppendLine("        _ptr = ptr;");
        sb.AppendLine("        Initialize();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    partial void Initialize();");

        // Internal pointer accessor for other wrappers
        sb.AppendLine();
        sb.Append("    internal ").Append(model.NativeName).Append("* NativePtr => _ptr;");
        sb.AppendLine();

        // Methods for function-pointer fields
        if (model.Methods.Count > 0)
        {
            foreach (var method in model.Methods)
            {
                sb.AppendLine();
                EmitMethod(sb, model, method);
            }
        }

        // Properties for data fields (data-only structs)
        if (model.DataFields.Count > 0 && !model.IsCefObject)
        {
            foreach (var field in model.DataFields)
            {
                sb.AppendLine();
                EmitDataProperty(sb, field);
            }
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    private static void EmitMethod(StringBuilder sb, CefStructModel model, CefMethodModel method)
    {
        // Handle method name conflicts with object members
        var methodName = method.MethodName;
        if (methodName is "GetType" or "ToString" or "Equals" or "GetHashCode")
            methodName += "_"; // e.g. GetType → GetType_

        // Method signature
        sb.Append("    public ").Append(method.ManagedReturnType)
          .Append(" ").Append(methodName).Append("(");

        for (int i = 0; i < method.Parameters.Count; i++)
        {
            if (i > 0) sb.Append(", ");
            var p = method.Parameters[i];
            sb.Append(p.ManagedType).Append(" ").Append(p.ParamName);
        }

        sb.AppendLine(")");
        sb.AppendLine("    {");

        // Collect string params for fixed blocks
        var stringParams = method.Parameters.FindAll(p => p.IsStringParam);
        var hasStrings = stringParams.Count > 0;

        // Emit fixed blocks for each string param
        if (hasStrings)
        {
            foreach (var sp in stringParams)
            {
                sb.Append("        fixed (char* _p").Append(sp.Index)
                  .Append(" = ").Append(sp.ParamName).AppendLine(")");
            }

            sb.AppendLine("        {");

            // Declare string struct locals inside fixed block
            foreach (var sp in stringParams)
            {
                sb.Append("            _cef_string_utf16_t _s").Append(sp.Index).AppendLine(";");
                sb.Append("            CefStringRef.FillFromPinned(&_s").Append(sp.Index)
                  .Append(", _p").Append(sp.Index).Append(", ").Append(sp.ParamName)
                  .AppendLine("?.Length ?? 0);");
            }
        }

        var bodyIndent = hasStrings
            ? "            "
            : "        ";

        // Marshal parameters: build native arg list
        var nativeArgs = new List<string> { "_ptr" };

        foreach (var p in method.Parameters)
        {
            if (p.IsStringParam)
            {
                nativeArgs.Add("&_s" + p.Index);
            }
            else if (p.IsCefObjectParam)
            {
                nativeArgs.Add(p.ParamName + " is null ? null : " + p.ParamName + "->NativePtr");
            }
            else
            {
                nativeArgs.Add(p.ParamName);
            }
        }

        // Call native
        if (method.ManagedReturnType == "void")
        {
            sb.Append(bodyIndent).Append("_ptr->").Append(method.FieldName)
              .Append("(").Append(string.Join(", ", nativeArgs)).AppendLine(");");
        }
        else
        {
            sb.Append(bodyIndent).Append("var _result = _ptr->").Append(method.FieldName)
              .Append("(").Append(string.Join(", ", nativeArgs)).AppendLine(");");
            sb.AppendLine();

            // Marshal return
            if (method.ReturnsUserFreeString)
            {
                sb.Append(bodyIndent).AppendLine("return CefStringRef.ToStringAndFree(_result);");
            }
            else if (method.ReturnsCefObject)
            {
                sb.Append(bodyIndent).Append("return _result != null ? new ")
                  .Append(method.ReturnCefObjectName).AppendLine("(_result) : null;");
            }
            else
            {
                sb.Append(bodyIndent).AppendLine("return _result;");
            }
        }

        // Close fixed blocks
        if (hasStrings)
        {
            sb.AppendLine("        }");
        }

        sb.AppendLine("    }");
    }

    private static void EmitDataProperty(StringBuilder sb, CefFieldModel field)
    {
        var propName = TypeMapper.SnakeToPascal(field.Name);

        if (field.IsStringValue)
        {
            // _cef_string_utf16_t embedded by value → CefString wrapper
            // We need to be careful: the CefString holds a pointer to the embedded field
            sb.Append("    public string? ").Append(propName).AppendLine();
            sb.AppendLine("    {");
            sb.Append("        get => new CefString(&_ptr->").Append(field.Name).AppendLine(").Value;");
            sb.Append("        set => new CefString(&_ptr->").Append(field.Name).AppendLine(").Value = value;");
            sb.AppendLine("    }");
        }
        else if (field.IsEnumType)
        {
            // Use raw native enum type (no Cef* wrapper yet)
            sb.Append("    public ").Append(field.NativeType)
              .Append(" ").Append(propName).AppendLine();
            sb.AppendLine("    {");
            sb.Append("        get => _ptr->").Append(field.Name).AppendLine(";");
            sb.Append("        set => _ptr->").Append(field.Name).AppendLine(" = value;");
            sb.AppendLine("    }");
        }
        else
        {
            sb.Append("    public ").Append(field.NativeType).Append(" ").Append(propName).AppendLine();
            sb.AppendLine("    {");
            sb.Append("        get => _ptr->").Append(field.Name).AppendLine(";");
            sb.Append("        set => _ptr->").Append(field.Name).AppendLine(" = value;");
            sb.AppendLine("    }");
        }
    }
}
